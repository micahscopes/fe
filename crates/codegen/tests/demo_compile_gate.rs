//! Demo compile-gate: one pure-Rust test per curated `demos/**` Fe source
//! that lowers it through the REAL compiler pipeline (the same driver calls
//! `fe web build` makes: `resolve_web_entry` + `WebBundle::compile`) and
//! asserts it compiles. For render-mode demos the emitted WGSL is also
//! independently naga-reparsed and validated against the browser capability
//! set (no SHADER_INT64), mirroring `wasm_e2e.rs`/`spirv_e2e.rs`'s own gates.
//!
//! This is the ground-truth check `DEMO_MODERNIZATION_PLAN.md`'s
//! "compile-sweep" needed: every demo source listed here must keep compiling
//! against the pinned compiler, or this test fails and says exactly which
//! one broke and why. Pure Rust: no browser, no chrome, no python, no .mjs.
//!
//! GPU-execute is out of scope here (no adapter in this sandbox); the pass
//! bar is "compiles and naga-validates," the same honesty label
//! `spirv_e2e.rs` already uses ("validated, NOT executed").
//!
//! Coverage:
//!   - every `demos/sketches/*/src/lib.fe` that declares an `actor ... uses
//!     (GpuProgram<WebGpuBackend>)` (known_color, rollcall_pipeline, cga3d,
//!     qcga, qcga_pencil, qcga_pencil_de, desargues, raymarch, mandelbrot,
//!     mandelbrot_proof_gpu, plasma, gradient, dec): entry/mode are
//!     DERIVED from the actor declaration, never hardcoded here, exactly as
//!     `fe web build` does with `--entry`/`--mode` omitted;
//!   - `demos/sketches/fmath`, a math-intrinsics library ingot with no
//!     render entry: diagnostics-only (it must still type-check);
//!   - `demos/sketches/qcga_pencil_de` is the sole canonical gallery view over
//!     the shared solved scene; the old vertex/fragment actor is retired and
//!     `qcga_pencil` retains only non-rendering solver/projection oracles;
//!   - `demos/capstones/mandelbrot/kernel.fe`: a standalone, non-actor GRID
//!     kernel (intentionally target-neutral, four backends; see its own
//!     README), compiled here in explicit grid mode;
//!   - the two legacy interactive demos whose kernel is a bare `pub fn`
//!     fixture, not (yet) an `actor`: `webgpu-clifford-interactive`
//!     (`clifford_frag_rgba`) and `webgpu-mandelbrot-interactive`
//!     (`mandel_view_frag`). Their SSOT source lives at
//!     `crates/codegen/tests/fixtures/spirv/*.fe` (see each demo's
//!     `.gitignore`: "Generated by the Fe compiler via: cargo run -p
//!     fe-codegen --example gen_*_interactive_demo"), so this test compiles
//!     that exact fixture in explicit render mode;
//!   - the two legacy interactive demos that DO ship a full, tracked ingot
//!     under their `gen*/app` directory (the canonical `render`/`verify`/
//!     `oracle uses (HostEffect, MainThread, mut Dispatch<WebGpuBackend>)`
//!     lanes, pre-dating the `actor` idiom): `webgpu-qcga3d-quadric`
//!     (`demos/webgpu-qcga3d-quadric/gen/app`) and `webgpu-cga-inversion`
//!     (`demos/webgpu-cga-inversion/gen-schedule32/app`), compiled here
//!     directly from their tracked source with the canonical policy their
//!     own `gen_*_demo.rs` generator uses.

