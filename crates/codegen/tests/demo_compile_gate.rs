/// The wasmtime-executed `update_view` export matches the independent oracle
/// over a deterministic synthetic gesture tape (a forced zoom-in burst, then
/// a seeded LCG mixed drag/wheel walk), feeding each reply forward as the
/// next state -- the exact runtime round-trip `fe-render-runtime.js`'s
/// `_applyGesture` performs. Asserts the clamps hold at every step and that
/// the tape visits every clamp arm (coverage, not just "never observed to
/// escape").
///
/// `ZOOM_MIN` is now the `Fixed<8>` depth floor (`~1e-27`) a purely random
/// 3-way `dzoom` walk cannot reach in any reasonable step budget: reaching it
/// from the declared init (`1.5`) takes about `ln(1e-27/1.5)/ln(0.875) ~= 469`
/// CONSECUTIVE zoom-in notches, vanishingly unlikely at random (unlike
/// `ZOOM_MAX`, ~6 consecutive zoom-out notches away, which the random walk
/// reaches easily). So the tape runs the ORIGINAL random walk FIRST (the
/// regime that actually exercises the centre clamps: panning sensitivity is
/// `2*zoom/res`, so it needs zoom to stay near a normal size, not buried at
/// the depth floor), then APPENDS `FORCE_ZOOM_IN_STEPS` deterministic zoom-in
/// notches (cursor centred, so the anchor term is near zero) to guarantee
/// `ZOOM_MIN` coverage from wherever the random walk left `zoom`. Every step,
/// forced or random, still runs through wasmtime and is checked against the
/// oracle.
#[test]
fn mandelbrot_update_view_matches_oracle_over_gesture_tape() {
    let bundle = compile_actor_ingot("demos/sketches/mandelbrot");
    let engine = wasmtime::Engine::default();
    let module =
        wasmtime::Module::new(&engine, &bundle.wasm).expect("wasmtime should load the module");
    let mut store = wasmtime::Store::new(&engine, ());
    let instance = wasmtime::Instance::new(&mut store, &module, &[])
        .expect("wasmtime should instantiate the mandelbrot sketch wasm");
    // `(f32 x15) -> (f32 x9)`: the arity exceeds wasmtime's typed-tuple
    // ergonomics, so the call goes through the untyped `Val` path (mirroring
    // `precision_fixed_oracle.rs`'s L=8 harness).
    let update_view = instance.get_func(&mut store, "update_view").expect(
        "`update_view` export should exist as (f32 x15) -> (f32 x9): 5 gesture args then the \
             10 flattened actor state fields (eight Expansion<4> centre words, zoom, res)",
    );

    // The tape's own start state (independent of view()'s deep init): a shallow
    // centre so pan actually reaches the centre clamps. Each axis is a four-word
    // `Expansion<4>` centre; the deep words begin at zero.
    let mut cx = [-0.5f32, 0.0, 0.0, 0.0];
    let mut cy = [0.0f32, 0.0, 0.0, 0.0];
    let mut zoom = 1.5f32;
    let res = MANDELBROT_RES;
    let mut results = vec![wasmtime::Val::F32(0); 9];

    let mut s: u64 = 0x5EED_1234_CAFE_F00D;
    let (mut hit_cx_lo, mut hit_cx_hi, mut hit_cy_lo, mut hit_cy_hi) = (0u32, 0u32, 0u32, 0u32);
    let (mut hit_zoom_lo, mut hit_zoom_hi) = (0u32, 0u32);
    const RANDOM_STEPS: usize = 3_000;
    // From the worst-case starting point the random phase can leave zoom at
    // (`ZOOM_MAX = 3.0`): `ln(1e-27/3.0)/ln(0.875) ~= 474`, so 520 gives
    // margin.
    const FORCE_ZOOM_IN_STEPS: usize = 520;
    const STEPS: usize = RANDOM_STEPS + FORCE_ZOOM_IN_STEPS;
    for step in 0..STEPS {
        let (dx, dy, dzoom, mx, my) = if step < RANDOM_STEPS {
            s = s
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            let r = s;
            // Wide pixel deltas (up to +-127px) and an occasionally
            // out-of-frame cursor so the walk actually reaches every centre
            // clamp, not just wanders near the default view.
            let dx = (((r >> 8) & 255) as i32 - 128) as f32;
            let dy = (((r >> 16) & 255) as i32 - 128) as f32;
            let dzoom = match (r >> 24) & 3 {
                0 => -1.0,
                1 => 1.0,
                _ => 0.0,
            };
            let mx = ((r >> 32) & 1023) as f32 - 256.0;
            let my = ((r >> 42) & 1023) as f32 - 256.0;
            (dx, dy, dzoom, mx, my)
        } else {
            // The deterministic zoom-in burst: no pan (dx=dy=0), cursor
            // centred (so the anchor term is near zero and the centre does
            // not drift), pure zoom-in.
            (0.0, 0.0, -1.0, res / 2.0, res / 2.0)
        };

        let args: [f32; 15] = [
            dx, dy, dzoom, mx, my, cx[0], cx[1], cx[2], cx[3], cy[0], cy[1], cy[2], cy[3], zoom,
            res,
        ];
        let vals: Vec<wasmtime::Val> = args
            .iter()
            .map(|v| wasmtime::Val::F32(v.to_bits()))
            .collect();
        update_view
            .call(&mut store, &vals, &mut results)
            .expect("update_view should run");
        let mut got = [0f32; 9];
        for (i, r) in results.iter().enumerate() {
            got[i] = match r {
                wasmtime::Val::F32(bits) => f32::from_bits(*bits),
                other => panic!("update_view result {i} must be f32, got {other:?}"),
            };
        }

        let (want_cx, want_cy, want_z) =
            mandelbrot_update_view_oracle(cx, cy, zoom, res, dx, dy, dzoom, mx, my);
        let want = [
            want_cx[0], want_cx[1], want_cx[2], want_cx[3], want_cy[0], want_cy[1], want_cy[2],
            want_cy[3], want_z,
        ];
        assert_eq!(
            got, want,
            "gesture-tape step {step}: wasm update_view(cx={cx:?}, cy={cy:?}, zoom={zoom}; \
             dx={dx},dy={dy},dz={dzoom},mx={mx},my={my}) = {got:?} must equal the oracle {want:?}"
        );

        cx = [got[0], got[1], got[2], got[3]];
        cy = [got[4], got[5], got[6], got[7]];
        zoom = got[8];
        if cx[0] <= MANDELBROT_CENTER_X_RANGE.0 {
            hit_cx_lo += 1;
        }
        if cx[0] >= MANDELBROT_CENTER_X_RANGE.1 {
            hit_cx_hi += 1;
        }
        if cy[0] <= MANDELBROT_CENTER_Y_RANGE.0 {
            hit_cy_lo += 1;
        }
        if cy[0] >= MANDELBROT_CENTER_Y_RANGE.1 {
            hit_cy_hi += 1;
        }
        if zoom <= MANDELBROT_ZOOM_RANGE.0 {
            hit_zoom_lo += 1;
        }
        if zoom >= MANDELBROT_ZOOM_RANGE.1 {
            hit_zoom_hi += 1;
        }
        assert!(
            (MANDELBROT_CENTER_X_RANGE.0..=MANDELBROT_CENTER_X_RANGE.1).contains(&cx[0]),
            "step {step}: center_x_w0 {} escaped its view() range",
            cx[0]
        );
        assert!(
            (MANDELBROT_CENTER_Y_RANGE.0..=MANDELBROT_CENTER_Y_RANGE.1).contains(&cy[0]),
            "step {step}: center_y_w0 {} escaped its view() range",
            cy[0]
        );
        assert!(
            (MANDELBROT_ZOOM_RANGE.0..=MANDELBROT_ZOOM_RANGE.1).contains(&zoom),
            "step {step}: zoom {zoom} escaped its view() range"
        );
    }

    assert!(
        hit_cx_lo > 0 && hit_cx_hi > 0 && hit_cy_lo > 0 && hit_cy_hi > 0,
        "the gesture tape must visit all four center clamps (cx_lo={hit_cx_lo}, cx_hi={hit_cx_hi}, \
         cy_lo={hit_cy_lo}, cy_hi={hit_cy_hi})"
    );
    assert!(
        hit_zoom_lo > 0 && hit_zoom_hi > 0,
        "the gesture tape must visit both zoom clamps (zoom_lo={hit_zoom_lo}, zoom_hi={hit_zoom_hi})"
    );
    eprintln!(
        "R3 step 1 tape: {STEPS} mixed pan/zoom/anchor events under wasmtime; the mandelbrot \
         update_view (Expansion<4> centre, 9-value reply) equals the independent oracle at EVERY \
         step. Clamp coverage: cx_lo={hit_cx_lo} cx_hi={hit_cx_hi} cy_lo={hit_cy_lo} \
         cy_hi={hit_cy_hi} zoom_lo={hit_zoom_lo} zoom_hi={hit_zoom_hi}."
    );
}

