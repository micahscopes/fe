/// Names of every FUNCTION export of a wasm module, in section order.
fn wasm_function_export_names(wasm: &[u8]) -> Vec<String> {
    use wasmparser::{ExternalKind, Payload};

    let mut names = Vec::new();
    for payload in wasmparser::Parser::new(0).parse_all(wasm) {
        if let Ok(Payload::ExportSection(reader)) = payload {
            for export in reader {
                let Ok(export) = export else { continue };
                if matches!(export.kind, ExternalKind::Func) {
                    names.push(export.name.to_owned());
                }
            }
        }
    }
    names
}

// ---------------------------------------------------------------------------
// Typed surface transition (mandelbrot): the gallery actor's `navigate`
// behavior is compiled under one fixed, versioned Wasm export. Fe owns pan
// sensitivity, raw-wheel interpretation, the zoom curve, cursor anchoring,
// clamps, complete state transitions, and resident state; JS transports raw
// event facts and retains returned values only as a presentation mirror.
//
// Gate: there is deliberately NO manifest control section, and the
// wasmtime-executed fixed export matches an oracle over a seeded synthetic
// event tape at EVERY step,
// mirroring `spirv_e2e.rs`'s `update_view_matches_oracle_over_gesture_tape`
// rigor for the `mandel_view_ctl.fe` fixture's i32 Q12 sibling.
// ---------------------------------------------------------------------------

const MANDELBROT_CENTER_X_RANGE: (f32, f32) = (-2.5, 1.0);
const MANDELBROT_CENTER_Y_RANGE: (f32, f32) = (-1.5, 1.5);
// The `Fixed<8>` zoom floor (~2^-91 ~ 1e-27): the per-pixel coordinate is
// carried at full `Fixed<8>` width, so the zoom is no longer bounded at the old
// ~1e-11 df64 wall; mirrors `lib.fe`'s `ZOOM_MIN`.
const MANDELBROT_ZOOM_RANGE: (f32, f32) = (0.000000000000000000000000001, 3.0);
const MANDELBROT_RES: f32 = 512.0;

/// Knuth's TwoSum, mirroring `lib.fe`'s `two_sum`: exact `a + b` as `(s, e)`
/// with `s + e == a + b` over the reals, plain f32 (no `f64`, no fused
/// multiply-add) so this stays bit-for-bit comparable to the wasm the same
/// source lowers to.
fn two_sum(a: f32, b: f32) -> (f32, f32) {
    let s = a + b;
    let bb = s - a;
    let err = (a - (s - bb)) + (b - bb);
    (s, err)
}

/// Mirrors `precision`'s general `Exp::add_corr` on a length-n expansion (index
/// 0 = most significant), verbatim: `two_sum` the leading terms, fold the error
/// down into the tail's own combine, then a FINAL `two_sum` re-normalizing this
/// level's leading term against whatever the tail settled on. Plain f32 (no
/// f64, no FMA), so this stays bit-for-bit comparable to the wasm the SAME
/// generic source lowers to. This is the N-general body the committed
/// `Expansion<2>` oracle proves bit-identical at N=2; here it drives N=4.
fn exp_add_corr(a: &[f32], b: &[f32], corr: f32) -> Vec<f32> {
    if a.len() == 1 {
        // The base case (`Last`): a plain "lump the rest" sum.
        vec![(corr + a[0]) + b[0]]
    } else {
        let (a0, ae) = two_sum(a[0], corr);
        let (s, e) = two_sum(a0, b[0]);
        let tail = exp_add_corr(&a[1..], &b[1..], ae + e);
        let (hi, lo) = two_sum(s, tail[0]);
        let mut out = Vec::with_capacity(a.len());
        out.push(hi); // this level's re-normalized leading term
        out.push(lo); // tail_result.with_head(lo)
        out.extend_from_slice(&tail[1..]);
        out
    }
}

/// Mirrors `lib.fe`'s `add_f32<4>(a, b)`: a four-word `Expansion<4>` `a` plus a
/// plain f32 `b`, via `a.add_corr(from_scalar(b), 0.0)` where
/// `from_scalar(b) = [b, 0, 0, 0]`.
fn qf_add_f32(a: [f32; 4], b: f32) -> [f32; 4] {
    let r = exp_add_corr(&a, &[b, 0.0, 0.0, 0.0], 0.0);
    [r[0], r[1], r[2], r[3]]
}

fn scaled_f32(value: f32, fractional_bits: i32) -> num_bigint::BigInt {
    let bits = value.to_bits();
    if bits & 0x7fff_ffff == 0 {
        return 0u32.into();
    }
    let exponent = ((bits >> 23) & 0xff) as i32 - 127;
    let significand = num_bigint::BigInt::from((1u32 << 23) | (bits & 0x7f_ffff));
    let shift = exponent - 23 + fractional_bits;
    let magnitude = if shift >= 0 {
        significand << shift as usize
    } else {
        significand >> (-shift) as usize
    };
    if bits >> 31 == 0 {
        magnitude
    } else {
        -magnitude
    }
}

fn scaled_expansion(words: [f32; 4], fractional_bits: i32) -> num_bigint::BigInt {
    words
        .into_iter()
        .map(|word| scaled_f32(word, fractional_bits))
        .sum()
}

#[test]
fn expansion4_pan_keeps_one_pixel_steps_through_declared_zoom_floor() {
    // A 160-bit integer scale represents every binary32 term here exactly.
    // This is a mathematical-value gate, not another copy of the expansion's
    // operation sequence: adding one backing pixel must move the represented
    // center in the requested direction, even when the change belongs in w3.
    const SCALE_BITS: i32 = 160;
    let center = [
        -0.7436438798904419,
        -0.0000000071467170,
        -0.0000000000000003,
        -0.00000000000000000000002,
    ];
    let before = scaled_expansion(center, SCALE_BITS);
    for zoom in [1.0e-12f32, 1.0e-18, 1.0e-24, 1.0e-27] {
        let pixel_step = 2.0 * zoom / MANDELBROT_RES;
        let after = scaled_expansion(qf_add_f32(center, pixel_step), SCALE_BITS);
        let observed = &after - &before;
        let expected = scaled_f32(pixel_step, SCALE_BITS);
        let error = &observed - &expected;
        assert!(
            observed > 0u32.into(),
            "zoom={zoom:e}: a positive one-pixel pan was lost or reversed ({observed})"
        );
        assert!(
            error.magnitude() * 2u32 < expected.magnitude().clone(),
            "zoom={zoom:e}: represented pan {observed} is not within half a pixel of {expected}"
        );
    }
}

/// Mirrors `lib.fe`'s `clamp_quad`: clamp a four-word `Expansion<4>` to an f32
/// range, comparing on `w0` only, dropping the trailing words to zero on a
/// clamp.
fn qf_clamp(w: [f32; 4], min_v: f32, max_v: f32) -> [f32; 4] {
    if w[0] < min_v {
        [min_v, 0.0, 0.0, 0.0]
    } else if w[0] > max_v {
        [max_v, 0.0, 0.0, 0.0]
    } else {
        w
    }
}

/// The independent oracle (re-derived from the pan/zoom/anchor/clamp spec:
/// pan follows the pointer via the actor's own pixel/complex-plane map, one
/// wheel notch is a fixed 7/8-in / 9/8-out zoom step, the anchor correction
/// uses the OLD zoom minus the NEW (clamped) zoom via that SAME map, clamps
/// apply last to the actor's declared `view()` ranges): `escape`'s own u/v
/// map is `u(px) = (px+0.5)/res*2-1` (screen right = complex right) and
/// `v(py) = 1-(py+0.5)/res*2` (screen DOWN = complex UP, the Y-flip), so a
/// downward drag increases `center_y` (opposite of the `dx`/`center_x` sign).
///
/// The complex-plane centre is a FOUR-WORD `Expansion<4>` (deep zoom ~1e-27):
/// pan and anchor deltas are O(zoom) quantities that fold into the four-word
/// centre through `add_f32<4>`, mirroring `lib.fe`'s `navigate` exactly
/// (same op sequence, same f32 rounding), so this oracle is expected to match
/// the wasm export BIT-FOR-BIT, not just within an epsilon.
fn mandelbrot_update_view_oracle(
    cx: [f32; 4],
    cy: [f32; 4],
    zoom: f32,
    res: f32,
    dx: f32,
    dy: f32,
    dzoom: f32,
    mx: f32,
    my: f32,
) -> ([f32; 4], [f32; 4], f32) {
    let step = 2.0 * zoom / res;
    let cx0 = qf_add_f32(cx, -dx * step);
    let cy0 = qf_add_f32(cy, dy * step);

    let stepped = if dzoom < 0.0 {
        zoom * 0.875
    } else if dzoom > 0.0 {
        zoom * 1.125
    } else {
        zoom
    };
    let z_c = stepped.clamp(MANDELBROT_ZOOM_RANGE.0, MANDELBROT_ZOOM_RANGE.1);

    let u = (mx + 0.5) * 2.0 / res - 1.0;
    let v = 1.0 - (my + 0.5) * 2.0 / res;
    let cx_a = qf_add_f32(cx0, u * (zoom - z_c));
    let cy_a = qf_add_f32(cy0, v * (zoom - z_c));

    let cx_c = qf_clamp(
        cx_a,
        MANDELBROT_CENTER_X_RANGE.0,
        MANDELBROT_CENTER_X_RANGE.1,
    );
    let cy_c = qf_clamp(
        cy_a,
        MANDELBROT_CENTER_Y_RANGE.0,
        MANDELBROT_CENTER_Y_RANGE.1,
    );
    (cx_c, cy_c, z_c)
}

