fn repo_root() -> PathBuf {
    // CARGO_MANIFEST_DIR is `crates/codegen`; two ancestors up is the repo root.
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/codegen should have a two-level ancestor (the repo root)")
        .to_path_buf()
}

/// Reparse the emitted WGSL with naga's `wgsl-in` front end and validate it
/// against the BROWSER capability set (`Capabilities::default()`, no
/// SHADER_INT64) -- independent of `WebBundle::compile`'s own internal gate
/// (belt and suspenders, matching the idiom every other e2e test here uses).
fn assert_browser_wgsl(wgsl: &str) {
    assert!(
        !wgsl.contains("i64") && !wgsl.contains("u64"),
        "browser-profile WGSL must contain no 64-bit scalar token:\n{wgsl}"
    );
    let module = naga::front::wgsl::parse_str(wgsl)
        .unwrap_or_else(|e| panic!("naga wgsl-in should reparse the emitted WGSL: {e:?}\n{wgsl}"));
    naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::default(),
    )
    .validate(&module)
    .unwrap_or_else(|e| panic!("browser-profile WGSL validation failed: {e:?}"));
}

fn assert_scheduled_typed_surface(bundle: &WebBundle) {
    assert!(
        bundle.manifest.control.is_none(),
        "typed surface control must not recreate the legacy JSON control protocol"
    );
    let exports = wasm_function_export_names(&bundle.wasm);
    assert!(
        exports
            .iter()
            .any(|name| name == "fe_surface_transition_latest_per_frame_v4"),
        "the Fe-declared latest-per-frame transition must use its fixed host ABI"
    );
    assert!(
        !exports
            .iter()
            .any(|name| name == "fe_surface_transition_v2"),
        "a scheduled actor must not also export the immediate transition ABI"
    );
    assert!(
        !exports
            .iter()
            .any(|name| name == "fe_surface_transition_latest_per_frame_v1"),
        "the host-coalesced v1 scheduling ABI must be absent"
    );
    assert!(exports.iter().any(|name| name == "fe_cabi_alloc"));
    assert!(exports.iter().any(|name| name == "fe_cabi_reset"));
    assert!(
        exports
            .iter()
            .any(|name| name == "fe_surface_state_replace_v1"),
        "a resident actor must expose its fixed complete-state replacement boundary"
    );
    assert!(
        !exports
            .iter()
            .any(|name| name == "fe_surface_transition_latest_per_frame_v2"),
        "the JavaScript-state-courier v2 ABI must be absent"
    );
    assert!(
        !exports.iter().any(|name| name == "navigate"),
        "an ordinary Fe behavior name must not leak into the host ABI"
    );
    assert!(
        !exports.iter().any(|name| name == "update_view"),
        "the reserved legacy gesture export must be absent"
    );
    assert!(
        bundle
            .manifest
            .provenance
            .fe_responsibilities
            .contains(&WebFeResponsibility::SchedulingPolicy)
    );
    assert!(
        bundle
            .manifest
            .provenance
            .fe_responsibilities
            .contains(&WebFeResponsibility::ResidentActorState)
    );
    assert!(
        bundle
            .manifest
            .provenance
            .fixed_host
            .responsibilities
            .contains(&WebHostResponsibility::PresentationClock)
    );
    assert!(
        !bundle
            .manifest
            .provenance
            .fixed_host
            .responsibilities
            .contains(&WebHostResponsibility::PresentationScheduler)
    );
}

