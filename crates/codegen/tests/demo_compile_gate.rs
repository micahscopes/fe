#[derive(Clone, Copy)]
struct SurfaceEventFixture {
    pointer_x: f32,
    pointer_y: f32,
    delta_x: f32,
    delta_y: f32,
    wheel_delta: f32,
    wheel_mode: u32,
    buttons: u32,
    timestamp: f32,
    width: f32,
    height: f32,
    event_kind: u32,
    param_index: u32,
    param_value: f32,
}

fn write_surface_event_batch(
    memory: &wasmtime::Memory,
    store: &mut wasmtime::Store<()>,
    pointer: usize,
    events: &[SurfaceEventFixture],
) {
    let mut bytes = Vec::with_capacity(events.len() * 52);
    for event in events {
        bytes.extend_from_slice(&event.pointer_x.to_le_bytes());
        bytes.extend_from_slice(&event.pointer_y.to_le_bytes());
        bytes.extend_from_slice(&event.delta_x.to_le_bytes());
        bytes.extend_from_slice(&event.delta_y.to_le_bytes());
        bytes.extend_from_slice(&event.wheel_delta.to_le_bytes());
        bytes.extend_from_slice(&event.wheel_mode.to_le_bytes());
        bytes.extend_from_slice(&event.buttons.to_le_bytes());
        bytes.extend_from_slice(&event.timestamp.to_le_bytes());
        bytes.extend_from_slice(&event.width.to_le_bytes());
        bytes.extend_from_slice(&event.height.to_le_bytes());
        bytes.extend_from_slice(&event.event_kind.to_le_bytes());
        bytes.extend_from_slice(&event.param_index.to_le_bytes());
        bytes.extend_from_slice(&event.param_value.to_le_bytes());
    }
    memory
        .write(store, pointer, &bytes)
        .expect("write raw SurfaceEvent batch");
}

/// Execute the fixed resident surface ABI used by the four scalar-state
/// gallery actors. The browser seeds complete state once; the frame call then
/// carries only a raw event batch. A four-value reply is a presentation
/// snapshot, while the same values also remain resident in the Wasm instance.
fn call_four_state_transition(
    bundle: &WebBundle,
    delta_x: f32,
    delta_y: f32,
    wheel_delta: f32,
    state: [f32; 4],
    width: f32,
) -> [f32; 4] {
    call_four_state_batch(
        bundle,
        &[SurfaceEventFixture {
            pointer_x: 123.25,
            pointer_y: 87.5,
            delta_x,
            delta_y,
            wheel_delta,
            wheel_mode: 1,
            buttons: 1,
            timestamp: 456.75,
            width,
            height: 480.0,
            event_kind: 0,
            param_index: 0,
            param_value: 0.0,
        }],
        state,
    )
}

fn call_four_state_batch(
    bundle: &WebBundle,
    events: &[SurfaceEventFixture],
    state: [f32; 4],
) -> [f32; 4] {
    call_state_batch(bundle, events, &state)
        .try_into()
        .expect("four-state fixture must return exactly four fields")
}

fn call_state_batch(bundle: &WebBundle, events: &[SurfaceEventFixture], state: &[f32]) -> Vec<f32> {
    assert!(
        !events.is_empty(),
        "surface frame fixture requires an event"
    );
    let engine = wasmtime::Engine::default();
    let module = wasmtime::Module::new(&engine, &bundle.wasm).expect("control Wasm module");
    let mut store = wasmtime::Store::new(&engine, ());
    let instance = wasmtime::Instance::new(&mut store, &module, &[]).expect("control instance");
    let transition = instance
        .get_func(&mut store, "fe_surface_transition_latest_per_frame_v4")
        .expect("scheduled typed surface transition export");
    let replace_state = instance
        .get_func(&mut store, "fe_surface_state_replace_v1")
        .expect("resident surface state replacement export");
    let memory = instance
        .get_memory(&mut store, "memory")
        .expect("scheduled transition exports linear memory");
    let alloc = instance
        .get_typed_func::<(i32, i32), i32>(&mut store, "fe_cabi_alloc")
        .expect("scheduled transition exports fixed allocator");
    let event_pointer = alloc
        .call(&mut store, ((events.len() * 52) as i32, 4))
        .expect("allocate raw SurfaceEvent batch") as usize;
    write_surface_event_batch(&memory, &mut store, event_pointer, events);
    let values = [
        wasmtime::Val::I32(event_pointer as i32),
        wasmtime::Val::I32(events.len() as i32),
    ];
    let mut uninitialized_results = vec![wasmtime::Val::F32(0); state.len()];
    assert!(
        transition
            .call(&mut store, &values, &mut uninitialized_results)
            .is_err(),
        "a resident frame must fail closed before complete state is seeded"
    );
    let state_values = state
        .iter()
        .map(|value| wasmtime::Val::F32(value.to_bits()))
        .collect::<Vec<_>>();
    replace_state
        .call(&mut store, &state_values, &mut [])
        .expect("seed complete resident Fe state");
    let mut results = vec![wasmtime::Val::F32(0); state.len()];
    transition
        .call(&mut store, &values, &mut results)
        .expect("Fe typed surface transition call");
    results
        .into_iter()
        .map(|value| match value {
            wasmtime::Val::F32(bits) => f32::from_bits(bits),
            other => panic!("typed surface transition returned non-f32 value {other:?}"),
        })
        .collect()
}

/// Run `body` with a checked-in ingot directory's driver database and top
/// module. `body` receives `&DriverDataBase` (borrowed, not moved) so the
/// caller can keep compiling against it (`resolve_web_entry`,
/// `WebBundle::compile`, ...).
fn with_ingot<R>(
    rel_dir: &str,
    body: impl FnOnce(&DriverDataBase, hir::hir_def::TopLevelMod<'_>) -> R,
) -> R {
    let dir = repo_root().join(rel_dir);
    let mut db = DriverDataBase::default();
    let url = Url::from_directory_path(&dir)
        .unwrap_or_else(|_| panic!("invalid ingot path {}", dir.display()));
    assert!(
        !driver::init_ingot(&mut db, &url),
        "{rel_dir}: ingot initialization diagnostics"
    );
    let ingot = db
        .workspace()
        .containing_ingot(&db, url)
        .unwrap_or_else(|| panic!("{rel_dir} did not resolve to one ingot"));
    let top_mod = ingot.root_mod(&db);
    let diagnostics = db.run_on_top_mod(top_mod).format_diags(&db);
    assert!(
        diagnostics.is_empty(),
        "{rel_dir}: source diagnostics prevent compilation:\n{diagnostics}"
    );
    body(&db, top_mod)
}

/// Run `body` with a standalone `.fe` FILE (no `fe.toml`, a fixture path)
/// loaded into its own driver database.
fn with_standalone_file<R>(
    rel_path: &str,
    body: impl FnOnce(&DriverDataBase, hir::hir_def::TopLevelMod<'_>) -> R,
) -> R {
    let file_path = repo_root().join(rel_path);
    let source = std::fs::read_to_string(&file_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", file_path.display()));
    let mut db = DriverDataBase::default();
    let url = Url::from_file_path(&file_path)
        .unwrap_or_else(|_| panic!("invalid file path {}", file_path.display()));
    db.workspace().touch(&mut db, url.clone(), Some(source));
    let file = db
        .workspace()
        .get(&db, &url)
        .unwrap_or_else(|| panic!("failed to load {}", file_path.display()));
    let top_mod = db.top_mod(file);
    let diagnostics = db.run_on_top_mod(top_mod).format_diags(&db);
    assert!(
        diagnostics.is_empty(),
        "{rel_path}: source diagnostics prevent compilation:\n{diagnostics}"
    );
    body(&db, top_mod)
}

/// Compile an ingot directory whose render/grid entry is DERIVED from its
/// `actor ... uses (GpuProgram<WebGpuBackend>)` declaration, exactly as
/// `fe web build` does with `--entry`/`--mode` omitted.
fn compile_actor_ingot(rel_dir: &str) -> WebBundle {
    with_ingot(rel_dir, |db, top_mod| {
        let (entry, mode) = resolve_web_entry(db, top_mod, None, None).unwrap_or_else(|e| {
            panic!("{rel_dir}: could not derive a render entry from the actor declaration: {e}")
        });
        let options = match mode {
            WebBundleMode::Render => WebBuildOptions::render(entry, Some(rel_dir.to_string())),
            WebBundleMode::Grid => panic!(
                "{rel_dir}: derived grid mode; no curated sketch is expected to be grid-shaped"
            ),
            WebBundleMode::Compute => {
                panic!("{rel_dir}: a compute stage must be part of an actor pass graph")
            }
        };
        WebBundle::compile(db, top_mod, options)
            .unwrap_or_else(|e| panic!("{rel_dir}: WebBundle::compile failed: {e}"))
    })
}

/// Compile an actor ingot after replacing only its root Fe source in the
/// in-memory workspace. Dependencies and package metadata remain the real
/// checked-in ingot, while a negative gate can perturb one semantic contract
/// without creating another fixture format or runtime manifest.
fn compile_actor_ingot_with_root_source(
    rel_dir: &str,
    source: String,
) -> Result<WebBundle, WebBundleError> {
    let dir = repo_root().join(rel_dir);
    let mut db = DriverDataBase::default();
    let dir_url = Url::from_directory_path(&dir)
        .unwrap_or_else(|_| panic!("invalid ingot path {}", dir.display()));
    assert!(
        !driver::init_ingot(&mut db, &dir_url),
        "{rel_dir}: ingot initialization diagnostics"
    );
    let source_url = Url::from_file_path(dir.join("src/lib.fe"))
        .unwrap_or_else(|_| panic!("invalid ingot root source path {}", dir.display()));
    db.workspace().update(&mut db, source_url.clone(), source);
    let ingot = db
        .workspace()
        .containing_ingot(&db, source_url)
        .unwrap_or_else(|| panic!("{rel_dir} root source did not resolve to its ingot"));
    let top_mod = ingot.root_mod(&db);
    let diagnostics = db.run_on_top_mod(top_mod).format_diags(&db);
    assert!(
        diagnostics.is_empty(),
        "{rel_dir}: mutated source diagnostics prevent contract testing:\n{diagnostics}"
    );
    let (entry, mode) = resolve_web_entry(&db, top_mod, None, None)?;
    let WebBundleMode::Render = mode else {
        panic!("{rel_dir}: negative surface contract fixture must remain render-shaped")
    };
    WebBundle::compile(
        &db,
        top_mod,
        WebBuildOptions::render(entry, Some(rel_dir.to_owned())),
    )
}

/// Analyze an ingot after replacing only its root Fe source. Unlike the bundle
/// helper above, this deliberately returns semantic diagnostics for negative
/// provider/generalization gates.
fn actor_ingot_root_diagnostics(rel_dir: &str, source: String) -> String {
    let dir = repo_root().join(rel_dir);
    let mut db = DriverDataBase::default();
    let dir_url = Url::from_directory_path(&dir)
        .unwrap_or_else(|_| panic!("invalid ingot path {}", dir.display()));
    assert!(
        !driver::init_ingot(&mut db, &dir_url),
        "{rel_dir}: ingot initialization diagnostics"
    );
    let source_url = Url::from_file_path(dir.join("src/lib.fe"))
        .unwrap_or_else(|_| panic!("invalid ingot root source path {}", dir.display()));
    db.workspace().update(&mut db, source_url.clone(), source);
    let ingot = db
        .workspace()
        .containing_ingot(&db, source_url)
        .unwrap_or_else(|| panic!("{rel_dir} root source did not resolve to its ingot"));
    db.run_on_top_mod(ingot.root_mod(&db)).format_diags(&db)
}

/// Compile a checked-in ingot directory in explicit render mode with the
/// canonical `render`/`verify`/`oracle` lanes required, matching the legacy
/// `render/verify/oracle uses (HostEffect, MainThread, mut
/// Dispatch<WebGpuBackend>)` demos' own `gen_*_demo.rs` generator.
fn compile_canonical_app(rel_dir: &str, entry: &str) -> WebBundle {
    with_ingot(rel_dir, |db, top_mod| {
        let options = WebBuildOptions::render(entry, Some(rel_dir.to_string()))
            .with_canonical_policy(WebCanonicalPolicy::Required)
            .with_canonical_entries(["render", "verify", "oracle"]);
        WebBundle::compile(db, top_mod, options)
            .unwrap_or_else(|e| panic!("{rel_dir}: WebBundle::compile failed: {e}"))
    })
}

/// Compile a standalone `.fe` fixture file in explicit render mode.
fn compile_standalone_render(rel_path: &str, entry: &str) -> WebBundle {
    with_standalone_file(rel_path, |db, top_mod| {
        let options = WebBuildOptions::render(entry, Some(rel_path.to_string()));
        WebBundle::compile(db, top_mod, options)
            .unwrap_or_else(|e| panic!("{rel_path}: WebBundle::compile failed: {e}"))
    })
}

/// Compile a standalone `.fe` fixture file in explicit grid mode.
